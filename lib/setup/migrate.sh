# mg_bullet_text LABEL: the 3.0 bullet, from the kit's template when it has the 3.0 wording.
# The backticks below are Markdown, written literally.
# shellcheck disable=SC2016
mg_bullet_text() {
    local label="$1" t="$MG_KIT/templates/workspace/projects.md" txt=""
    if [[ -f "$t" ]]; then
        txt="$(awk -v lab="**$label:**" '
            /^[ \t]*[-*][ \t]+/ { if (on) exit; if (index($0, lab)) { on = 1; print; next } }
            on && /^[ \t]+[^ \t]/ { print; next }
            on { exit }' "$t")"
    fi
    case "$label" in
        Done)   [[ "$txt" == *'`projects/_done/<slug>/`'* ]] && { printf '%s\n' "$txt"; return; }
                printf '%s\n' '- **Done:** `projects/_done/<slug>/` — `/projects:close` moves the folder here, keeping history: `git mv`' \
                    '  for a project tracked by the workspace or its own repository, and a plain move plus a `.gitignore`' \
                    '  line for an untracked one.' ;;
        Paused) [[ "$txt" == *'/projects:hold'* ]] && { printf '%s\n' "$txt"; return; }
                printf '%s\n' '- **Paused:** `projects/<slug>/` — the folder stays where it is and stays versioned; its register row' \
                    '  moves to the Paused section (`/projects:hold`).' ;;
    esac
}
# mg_edit_bullet LABEL NEWVALUE: replaces the bullet (with its continuation lines) in the conventions.
mg_edit_bullet() {
    local label="$1" newv="$2" ph n out="$MG_TMP/conv"
    ph="$(mg_vphys .claude/projects.md)" || return 0
    mg_bullet_text "$label" > "$MG_TMP/bullet"
    n="$(awk -v lab="**$label:**" -v nb="$MG_TMP/bullet" -v out="$out" '
        BEGIN { while ((getline l < nb) > 0) B[++nb_n] = l }
        skip && /^[ \t]+[^ \t]/ && !/^[ \t]*[-*][ \t]+/ { next }
        { skip = 0 }
        !done && /^[ \t]*[-*][ \t]+/ && index($0, lab) {
            for (i = 1; i <= nb_n; i++) print B[i] > out
            done = 1; skip = 1; print NR; next
        }
        { print > out }' "$ph")"
    if [[ -z "$n" ]]; then mg_act skip "$label: setting (.claude/projects.md has none)"; return 0; fi
    mg_act edit ".claude/projects.md:$n $label: -> \`$newv\`"
    mg_vwrite .claude/projects.md < "$out"
    mg_plan .claude/projects.md; MG_EDITED+=(.claude/projects.md)
}
