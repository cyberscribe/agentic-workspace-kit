#!/usr/bin/env bash
# shellcheck source-path=SCRIPTDIR
# lib/setup/migrate.sh: kit/setup.sh migrate. Moves a workspace from the 2.x layout (the kit checked
# out at another path, its plugins vendored into .claude/plugins, generated skills in skills/, copies
# of kit files beside the team's own) to the 3.0 layout, where the kit is a submodule at kit/ and is
# read in place.
#
#   migrate.sh --target WS [--dry-run] [--map FILE] [--kit-from URL] [--kit-ref REF]
#              [--allow-staged] [--developer] [--confirm-private-origin]
#
# It knows only the kit's own moves. A workspace's own moves (folders renamed, content untracked,
# references rewritten) come from a map file, whose format is in kit/docs/migration.md.
#
# How it behaves:
#   - Every action prints one line, naming what it does, before it does it. The verbs are move,
#     retire, edit, config, run, note and skip. A dry run prints the same lines with "would " in front
#     and changes nothing in the workspace.
#   - Nothing is deleted. "retire" takes a path out of the index (when it is tracked) and moves it
#     under _delete/, which is gitignored; a person deletes it.
#   - Each step checks whether it is already done, so a second run prints only skip lines, and a run
#     stopped partway resumes.
#   - Nothing is committed. The run ends with the commit to make, by path.
#   - Opaque files (AW_OPAQUE_PATHS, by default AGENTS.md and copilot-instructions.md) are never read,
#     written, moved or renamed.
#
# The dry run and the real run print the same lines. To make that true without touching the
# workspace, a dry run keeps a small overlay in a temporary folder: the files it would have edited
# (the "shadow"), and a list of the moves and removals it would have made (the "ops"). Every later
# step reads the workspace through that overlay, so it sees what the real run would see at that point.
#
# Exit codes: 0 complete (or a dry run); 1 a precondition; 2 usage or a malformed map; 3 stopped at a
# failing step, which it names. The script runs under bash 3.2 and needs git and jq.
set -uo pipefail

MG_SELF_KIT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd -P)"
# shellcheck source=../common.sh
. "$MG_SELF_KIT/lib/common.sh"

MG_DEFAULT_URL="https://github.com/cyberscribe/agentic-workspace-kit.git"
MG_MARKER="Generated by install.sh from plugins/"
MG_IMPORT="@kit/CLAUDE.kit.md"
# The backticks in these strings are Markdown, written literally.
# shellcheck disable=SC2016
MG_FALLBACK='Kit working standards: `kit/CLAUDE.kit.md` (read it at session start if the line above was not expanded).'
MG_KIT_HEADER="# Added by the agentic workspace kit (kit/templates/workspace.gitignore)"

mg_usage() {
    cat <<'EOF'
Usage: kit/setup.sh migrate [--target DIR] [--dry-run] [--map FILE] [--kit-from URL] [--kit-ref REF]
                            [--allow-staged] [--developer] [--confirm-private-origin]

Moves a 2.x workspace to the 3.0 layout: the kit becomes the submodule at kit/, the vendored plugins,
generated skills and unchanged copies of kit files move to _delete/, references to the old kit path
are rewritten, the hooks and submodule settings are set, and the files the kit now leaves to you are
created. Every action is printed before it is made; nothing is deleted and nothing is committed.

  --dry-run                  print what would happen, and change nothing
  --map FILE                 the workspace's own moves (format: kit/docs/migration.md); keep it
                             outside kit/
  --kit-from URL             bring the kit checkout to REF from URL first (also AW_KIT_URL)
  --kit-ref REF              the kit commit, branch or tag to migrate to (default main)
  --allow-staged             run although the index has staged changes
  --developer                also put kit/ on main for kit development (kit/setup.sh --developer)
  --confirm-private-origin   record origin as a private remote you have confirmed yourself, in
                             .claude/workspace.md under Private remotes

Run it with --dry-run first, then without.
EOF
}

# ---- Arguments -----------------------------------------------------------------------------------
WS="" DRY=0 MAP="" KIT_FROM="${AW_KIT_URL:-}" KIT_REF="main" ALLOW_STAGED=0 DEVELOPER=0 CONFIRM_ORIGIN=0
while [[ $# -gt 0 ]]; do
    case "$1" in
        --target) [[ $# -ge 2 ]] || { mg_usage >&2; exit 2; }; WS="$2"; shift 2 ;;
        --target=*) WS="${1#--target=}"; shift ;;
        --dry-run) DRY=1; shift ;;
        --map) [[ $# -ge 2 ]] || { mg_usage >&2; exit 2; }; MAP="$2"; shift 2 ;;
        --map=*) MAP="${1#--map=}"; shift ;;
        --kit-from) [[ $# -ge 2 ]] || { mg_usage >&2; exit 2; }; KIT_FROM="$2"; shift 2 ;;
        --kit-from=*) KIT_FROM="${1#--kit-from=}"; shift ;;
        --kit-ref) [[ $# -ge 2 ]] || { mg_usage >&2; exit 2; }; KIT_REF="$2"; shift 2 ;;
        --kit-ref=*) KIT_REF="${1#--kit-ref=}"; shift ;;
        --allow-staged) ALLOW_STAGED=1; shift ;;
        --developer) DEVELOPER=1; shift ;;
        --confirm-private-origin) CONFIRM_ORIGIN=1; shift ;;
        -h|--help) mg_usage; exit 0 ;;
        *) printf 'migrate: unknown option %s\n\n' "$1" >&2; mg_usage >&2; exit 2 ;;
    esac
done
[[ -n "$WS" ]] || { printf 'migrate: --target is required\n\n' >&2; mg_usage >&2; exit 2; }
[[ -d "$WS" ]] || { printf 'migrate: %s is not a folder\n' "$WS" >&2; exit 1; }
WS="$(cd "$WS" && pwd -P)"

for mg_tool in git jq; do
    command -v "$mg_tool" >/dev/null 2>&1 || { printf 'migrate: needs %s on PATH\n' "$mg_tool" >&2; exit 1; }
done

# A temporary folder for the dry run's overlay and for scratch files. AW_KEEP=1 leaves it in place.
MG_TMP="$(mktemp -d "${TMPDIR:-/tmp}/aw-migrate.XXXXXX")" || { echo "migrate: cannot create a temporary folder" >&2; exit 1; }
if [[ "${AW_KEEP:-}" != "1" ]]; then trap 'rm -rf "$MG_TMP"' EXIT; fi
SHADOW="$MG_TMP/shadow" OPS="$MG_TMP/ops"
mkdir -p "$SHADOW" && : > "$OPS"

# ---- Git helpers ---------------------------------------------------------------------------------
# Reads in the workspace never take optional locks; writes go through mg_gw.
mg_g()  { git --no-optional-locks -C "$WS" "$@"; }
mg_gw() { git -C "$WS" "$@"; }

# A URL with no scheme and no scp form is a local path; git clones and fetches of one need the file
# protocol allowed explicitly. mg_proto URL sets MG_PC to that setting, or to nothing.
MG_PC=""
mg_proto() { MG_PC=""; case "$(aw_norm_url "$1")" in local:*) MG_PC="protocol.file.allow=always" ;; esac; }

# ---- Output --------------------------------------------------------------------------------------
# mg_act VERB TEXT: one action line; in a dry run, "would " comes first.
MG_ACTED=0
mg_act() {
    case "$1" in skip|note) ;; *) MG_ACTED=$((MG_ACTED + 1)) ;; esac
    if [[ $DRY -eq 1 ]]; then printf 'would %s %s\n' "$1" "$2"; else printf '%s %s\n' "$1" "$2"; fi
}
# mg_do VERB TEXT: an action line that does not count as a change to the workspace (bringing the kit
# checkout to the version to migrate to).
mg_do() { printf '%s %s\n' "$1" "$2"; }
# mg_would VERB TEXT: the dry run's line for an mg_do action, which it does not make.
mg_would() { printf 'would %s %s\n' "$1" "$2"; }
# mg_preview CMD...: in a dry run, what a step handed to another script would change, indented under
# its would-run line: the child's own check output, with "would " before each "set" line.
mg_preview() { "$@" 2>/dev/null | sed -e 's/^set /would set /' -e 's/^/    /'; return 0; }
# mg_child CMD...: a child's output, indented under the run line that names it.
mg_child() { "$@" 2>&1 | sed 's/^/    /'; return "${PIPESTATUS[0]}"; }

MG_STAGED_MARK=""
mg_mark_staged() {
    [[ $DRY -eq 1 || -z "$MG_STAGED_MARK" ]] && return 0
    mg_g ls-files -s 2>/dev/null | git hash-object --stdin > "$MG_STAGED_MARK" 2>/dev/null
    return 0
}
mg_stop() {
    printf 'migrate: stopped at %s: %s\n' "$1" "$2" >&2
    printf 'Nothing after this step was done. Fix the cause and run the migration again; it resumes.\n' >&2
    mg_mark_staged
    mg_save_state "$1"
    exit 3
}

# A run that stops leaves what the commit plan and the leftover-reference check (M18) need in
# aw-migrate-state, beside aw-migrate-index: the paths to add, the staged moves and removals, the
# moves. The run that resumes reads it back while HEAD has not moved, so its plan and its M18 cover the
# whole migration and not only its own part. A run that finishes removes the file.
MG_STATE_FILE="" MG_PRIOR_ACTED=0 MG_PRIOR_STOP=""
mg_save_state() {
    local p i
    [[ $DRY -eq 1 || -z "$MG_STATE_FILE" ]] && return 0
    {
        printf 'head\t%s\n' "$(mg_g rev-parse -q --verify HEAD 2>/dev/null)"
        printf 'stopped\t%s\n' "$1"
        printf 'acted\t%s\n' "$((MG_ACTED + MG_PRIOR_ACTED))"
        [[ $MG_EDITED_GITIGNORE -eq 1 ]] && printf 'gitignore\t1\n'
        for p in ${MG_PLAN[@]+"${MG_PLAN[@]}"}; do printf 'P\t%s\n' "$p"; done
        for p in ${MG_STAGED[@]+"${MG_STAGED[@]}"}; do printf 'S\t%s\n' "$p"; done
        i=0
        while [[ $i -lt ${#MG_MOVED_FROM[@]} ]]; do
            printf 'M\t%s\t%s\n' "${MG_MOVED_FROM[$i]}" "${MG_MOVED_TO[$i]}"
            i=$((i + 1))
        done
    } > "$MG_STATE_FILE" 2>/dev/null
    return 0
}

# Quoting for a path in a command printed for a person: single quotes when it needs any.
mg_q() { case "$1" in *[!A-Za-z0-9._/@:+=,-]*) printf "'%s'" "$(printf '%s' "$1" | sed "s/'/'\\\\''/g")" ;; *) printf '%s' "$1" ;; esac; }

# ---- The workspace as the run sees it ------------------------------------------------------------
# In a real run these read the workspace directly. In a dry run they read it through the overlay:
# the ops file records "M<TAB>from<TAB>to" (a move), "G<TAB>path" (retired) and "U<TAB>path"
# (untracked); the shadow folder holds edited copies at their workspace-relative paths.

# mg_vorig PATH: sets MG_ORIG to the path in the real tree that PATH stands for, and MG_UNTR to 1 when
# an untrack covers it. Returns 1 when PATH has been moved away or retired.
MG_ORIG="" MG_UNTR=0
mg_vorig() {
    local p="$1" t a b
    MG_UNTR=0
    if [[ $DRY -eq 1 && -s "$OPS" ]]; then
        while IFS=$'\t' read -r t a b; do
            case "$t" in
                M) if [[ "$p" == "$b" || "$p" == "$b/"* ]]; then p="$a${p#"$b"}"; continue; fi
                   if [[ "$p" == "$a" || "$p" == "$a/"* ]]; then return 1; fi ;;
                G) if [[ "$p" == "$a" || "$p" == "$a/"* ]]; then return 1; fi ;;
                U) if [[ "$p" == "$a" || "$p" == "$a/"* ]]; then MG_UNTR=1; fi ;;
            esac
        done < <(awk '{ l[NR] = $0 } END { for (i = NR; i >= 1; i--) print l[i] }' "$OPS")
    fi
    MG_ORIG="$p"
    return 0
}
mg_vexists() {
    [[ $DRY -eq 1 && -e "$SHADOW/$1" ]] && return 0
    mg_vorig "$1" || return 1
    [[ -e "$WS/$MG_ORIG" || -L "$WS/$MG_ORIG" ]]
}
# mg_vphys PATH: the file to read for PATH (the shadow copy when there is one).
mg_vphys() {
    if [[ $DRY -eq 1 && -e "$SHADOW/$1" ]]; then printf '%s\n' "$SHADOW/$1"; return 0; fi
    mg_vorig "$1" || return 1
    printf '%s\n' "$WS/$MG_ORIG"
}
mg_vread() { local f; f="$(mg_vphys "$1")" || return 1; [[ -f "$f" ]] || return 1; cat "$f"; }
# mg_vwrite PATH: stdin becomes PATH (in the shadow, in a dry run). The file keeps its mode.
mg_vwrite() {
    local dest="$WS/$1"
    if [[ $DRY -eq 1 ]]; then
        dest="$SHADOW/$1"
        if [[ ! -e "$dest" ]]; then mkdir -p "$(dirname "$dest")"; fi
    else
        mkdir -p "$(dirname "$dest")"
    fi
    cat > "$dest"
}
# mg_vtracked PATH: 0 when anything at or under PATH is tracked (a gitlink included).
mg_vtracked() {
    mg_vorig "$1" || return 1
    [[ $MG_UNTR -eq 0 ]] || return 1
    [[ -n "$(mg_g ls-files -- "$MG_ORIG" 2>/dev/null | head -n 1)" ]]
}
mg_vgitlink() {
    mg_vorig "$1" || return 1
    [[ $MG_UNTR -eq 0 ]] || return 1
    mg_g ls-files -s -- "$MG_ORIG" 2>/dev/null | awk -v p="$MG_ORIG" '$1 == "160000" && substr($0, index($0, "\t") + 1) == p { f = 1 } END { exit !f }'
}
mg_op() { [[ $DRY -eq 1 ]] && printf '%s\n' "$*" >> "$OPS"; return 0; }
# A dry-run move carries the shadow copies with it.
mg_shadow_move() {
    [[ $DRY -eq 1 && -e "$SHADOW/$1" ]] || return 0
    mkdir -p "$(dirname "$SHADOW/$2")" && mv "$SHADOW/$1" "$SHADOW/$2"
}

# mg_vlist: "path<TAB>file" for every tracked file (gitlinks and symlinks left out) as the tree stands
# now in this run: the path in the workspace, and the file to read for it.
mg_vlist() {
    local shl="$MG_TMP/shadow-list"
    : > "$shl"
    if [[ $DRY -eq 1 ]]; then (cd "$SHADOW" && find . -type f | sed 's#^\./##') > "$shl"; fi
    mg_g ls-files -s -z 2>/dev/null | tr '\0' '\n' | awk -v dry="$DRY" -v ops="$OPS" -v sh="$SHADOW" -v ws="$WS" -v shl="$shl" '
        BEGIN {
            n = 0
            if (dry) {
                while ((getline l < ops) > 0) { n++; split(l, f, "\t"); T[n] = f[1]; A[n] = f[2]; B[n] = f[3] }
                while ((getline l < shl) > 0) S[l] = 1
            }
        }
        {
            # Gitlinks are other repositories; a tracked symlink may point into a cloud drive.
            split($0, m, " "); if (m[1] == "160000" || m[1] == "120000") next
            o = substr($0, index($0, "\t") + 1); if (seen[o]++) next
            p = o
            for (i = 1; i <= n; i++) {
                if (p == A[i] || index(p, A[i] "/") == 1) {
                    if (T[i] == "M") p = B[i] substr(p, length(A[i]) + 1)
                    else { p = ""; break }
                }
            }
            if (p == "") next
            print p "\t" ((p in S) ? sh "/" p : ws "/" o)
        }'
}

# The opaque files that exist here. They are never opened, so every scan leaves them out.
MG_OPAQUE=()
mg_opaque_init() {
    local list p
    if [[ -n "${AW_OPAQUE_PATHS+set}" ]]; then list="$AW_OPAQUE_PATHS"; else list="AGENTS.md copilot-instructions.md"; fi
    for p in $list; do aw_is_opaque "$WS" "$p" && MG_OPAQUE+=("$p"); done
    return 0
}
mg_is_opaque() { local o; for o in ${MG_OPAQUE[@]+"${MG_OPAQUE[@]}"}; do [[ "$1" == "$o" ]] && return 0; done; return 1; }
# A path that is, holds, or sits inside an opaque file.
mg_touches_opaque() {
    local o
    for o in ${MG_OPAQUE[@]+"${MG_OPAQUE[@]}"}; do
        [[ "$1" == "$o" || "$o" == "$1/"* || "$1" == "$o/"* ]] && return 0
    done
    return 1
}
# Dated records keep their wording: logs/, _delete/, projects/_done/, any file named for decisions, and
# what a map's historical lines name.
MG_HIST_GLOBS=()
mg_is_historical() {
    case "$1" in logs/*|_delete/*|projects/_done/*) return 0 ;; esac
    case "${1##*/}" in *decisions*) return 0 ;; esac
    mg_map_historical "$1"
}
# A path a map's historical line names: its glob matches the path, or a folder it matches holds it.
# Glob matching as git's default pathspec does it: * crosses folders.
mg_map_historical() {
    local g
    for g in ${MG_HIST_GLOBS[@]+"${MG_HIST_GLOBS[@]}"}; do
        # shellcheck disable=SC2053
        [[ "$1" == $g || "$1" == $g/* ]] && return 0
    done
    return 1
}

# mg_candidates FIXED [scope]: "path<TAB>file" for tracked text files that contain FIXED, outside the
# kit, opaque files and .gitmodules. Scope "all" keeps historical records in; "globs" takes the
# globs in MG_GLOBS instead of the default set; "ext" limits to the extensions the kit path rewrite
# reads.
MG_GLOBS=()
mg_candidates() {
    local fixed="$1" scope="${2:-all}" list="$MG_TMP/cand-list" pre="$MG_TMP/cand-pre" hits="$MG_TMP/cand-hits"
    local vp ph g keep
    : > "$list"
    # The fixed exclusions in one pass: the kit, .gitmodules, opaque files, and (for "ext") the file
    # types the kit path rewrite reads.
    mg_vlist | awk -F '\t' -v scope="$scope" -v opq="${MG_OPAQUE[*]+${MG_OPAQUE[*]}}" '
        BEGIN { n = split(opq, O, " ") }
        {
            vp = $1
            if (vp == "kit" || index(vp, "kit/") == 1 || vp == ".gitmodules") next
            for (i = 1; i <= n; i++) if (vp == O[i] || index(vp, O[i] "/") == 1) next
            if (scope == "ext" && vp !~ /\.(md|json|sh|py|txt|yml)$/) next
            print
        }' > "$pre"
    if [[ "$scope" == globs ]]; then
        while IFS=$'\t' read -r vp ph; do
            keep=0
            for g in ${MG_GLOBS[@]+"${MG_GLOBS[@]}"}; do
                # Glob matching as git's default pathspec does it: * crosses folders.
                # shellcheck disable=SC2053
                [[ "$vp" == $g ]] && { keep=1; break; }
            done
            [[ $keep -eq 1 ]] && printf '%s\t%s\n' "$vp" "$ph" >> "$list"
        done < "$pre"
    else
        cat "$pre" > "$list"
    fi
    [[ -s "$list" ]] || return 0
    cut -f 2 "$list" | tr '\n' '\0' | xargs -0 grep -l -I -F -e "$fixed" -- > "$hits" 2>/dev/null
    awk -F '\t' -v hits="$hits" 'BEGIN { while ((getline l < hits) > 0) H[l] = 1 } ($2 in H)' "$list"
}

# mg_replace FILE OUT FROM TO MODE [KEEPFILE]: writes FILE with FROM replaced by TO to OUT and prints
# the numbers of the lines it changed. MODE "any" replaces every occurrence; "path" only where FROM
# follows the start of a line, a space, a tab, ( [ ` ' " or /; "word" the same without /; "ref" as
# "path", and not followed by a letter, a digit, _ or - (a whole path, for the leftover check). An
# occurrence inside a literal listed in KEEPFILE, or inside an occurrence of TO (text already
# rewritten), is left alone. With OUT empty it only reports.
mg_replace() {
    awk -v from="$3" -v to="$4" -v mode="$5" -v keepf="${6:-}" -v out="$2" '
        BEGIN {
            nk = 0
            if (keepf != "") while ((getline l < keepf) > 0) if (l != "") K[++nk] = l
            if (to != "" && index(to, from)) K[++nk] = to
            bset = " \t([`\047\""; if (mode == "path" || mode == "ref") bset = bset "/"
            lf = length(from)
        }
        function protect(line, lit,    s, i, p, k) {
            s = 1
            while ((i = index(substr(line, s), lit)) > 0) {
                p = s + i - 1
                for (k = p; k < p + length(lit); k++) PR[k] = 1
                s = p + 1
            }
        }
        {
            line = $0; split("", PR)
            for (j = 1; j <= nk; j++) protect(line, K[j])
            res = ""; s = 1; changed = 0
            while ((i = index(substr(line, s), from)) > 0) {
                p = s + i - 1; ok = 1
                for (k = p; k < p + lf; k++) if (k in PR) { ok = 0; break }
                if (ok && mode != "any" && p > 1 && index(bset, substr(line, p - 1, 1)) == 0) ok = 0
                if (ok && mode == "ref" && substr(from, lf, 1) != "/" && substr(line, p + lf, 1) ~ /[A-Za-z0-9_-]/) ok = 0
                if (ok) { res = res substr(line, s, p - s) to; s = p + lf; changed = 1 }
                else { res = res substr(line, s, p - s + 1); s = p + 1 }
            }
            res = res substr(line, s)
            if (out != "") print res > out
            if (changed) print NR
        }' "$1"
}

# ---- .gitignore ----------------------------------------------------------------------------------
mg_ignore_has() { mg_vread .gitignore 2>/dev/null | awk -v l="$1" '{ sub(/[ \t]+$/, "") } $0 == l { f = 1 } END { exit !f }'; }
# mg_ignore_add LINE [kit]: appends LINE; with "kit", under the kit's header, written once.
mg_ignore_add() {
    local line="$1" kit="${2:-}" cur="$MG_TMP/gi"
    mg_vread .gitignore > "$cur" 2>/dev/null || : > "$cur"
    if [[ -s "$cur" && -n "$(tail -c 1 "$cur")" ]]; then printf '\n' >> "$cur"; fi
    if [[ "$kit" == kit ]] && ! grep -qxF "$MG_KIT_HEADER" "$cur"; then
        [[ -s "$cur" ]] && printf '\n' >> "$cur"
        printf '%s\n' "$MG_KIT_HEADER" >> "$cur"
    fi
    printf '%s\n' "$line" >> "$cur"
    mg_vwrite .gitignore < "$cur"
    MG_EDITED_GITIGNORE=1
}
MG_EDITED_GITIGNORE=0
# _delete/ is ignored before anything is moved into it, so a broad git add never sweeps it up.
mg_ensure_delete_ignored() {
    mg_ignore_has "_delete/" && return 0
    mg_ignore_has "/_delete/" && return 0
    mg_act edit ".gitignore: + _delete/ (what the migration retires waits there for a person to delete it)"
    mg_ignore_add "_delete/" kit
}
# mg_ignored_by PATH: the .gitignore line that ignores PATH, as source:line:pattern, or nothing.
mg_ignored_by() { mg_g check-ignore -v --no-index -- "$1" 2>/dev/null | awk -F '\t' '{ print $1; exit }'; }

# ---- Actions -------------------------------------------------------------------------------------
MG_PLAN=()        # paths to name in the git add line
MG_STAGED=()      # removals and moves the migration staged itself
MG_MOVED_FROM=()  # sources of moves, for the leftover-reference check (M18)
MG_MOVED_TO=()
MG_EDITED=()
mg_plan() { MG_PLAN+=("$1"); }

# mg_retire STEP PATH: out of the index when tracked, then moved under _delete/.
mg_retire() {
    local step="$1" p="$2" dest="_delete/$2"
    if mg_touches_opaque "$p"; then mg_act skip "$step $p (opaque here: left as it is)"; return 0; fi
    if ! mg_vexists "$p"; then mg_act skip "$step $p (not present here)"; return 0; fi
    if mg_vexists "$dest"; then mg_act skip "$step $p (destination exists: $dest)"; return 0; fi
    mg_ensure_delete_ignored
    mg_act retire "$p -> $dest"
    if [[ $DRY -eq 1 ]]; then
        mg_op "G	$p"
    else
        if mg_vtracked "$p"; then
            mg_gw rm -r --cached -q -- "$p" || mg_stop "$step" "git rm --cached $p failed"
        fi
        if ! { mkdir -p "$WS/$(dirname "$dest")" && mv "$WS/$p" "$WS/$dest"; }; then mg_stop "$step" "moving $p to $dest failed"; fi
    fi
    MG_STAGED+=("$p"); MG_MOVED_FROM+=("$p"); MG_MOVED_TO+=("kit/$p")
    return 0
}

# mg_move STEP FROM TO HOW: HOW is "git mv" or "mv". Parents of TO are created.
mg_move() {
    local step="$1" from="$2" to="$3" how="$4"
    mg_act move "$from -> $to ($how)"
    if [[ $DRY -eq 1 ]]; then
        mg_op "M	$from	$to"
        mg_shadow_move "$from" "$to"
    else
        mkdir -p "$WS/$(dirname "$to")" || mg_stop "$step" "cannot create the folder for $to"
        if [[ "$how" == "git mv" ]]; then
            mg_gw mv -- "$from" "$to" || mg_stop "$step" "git mv $from $to failed"
        else
            mv "$WS/$from" "$WS/$to" || mg_stop "$step" "mv $from $to failed"
        fi
    fi
    MG_MOVED_FROM+=("$from"); MG_MOVED_TO+=("$to")
    if [[ "$how" == "git mv" ]]; then MG_STAGED+=("$from"); fi
    mg_plan "$to"
}

# mg_rewrite_in PATH FROM TO MODE [KEEPFILE] [LABEL]: rewrites one file, one edit line per line
# changed.
mg_rewrite_in() {
    local vp="$1" from="$2" to="$3" mode="$4" keepf="${5:-}" ph out="$MG_TMP/rw-out" nums n
    ph="$(mg_vphys "$vp")" || return 0
    nums="$(mg_replace "$ph" "$out" "$from" "$to" "$mode" "$keepf")"
    [[ -n "$nums" ]] || return 0
    for n in $nums; do mg_act edit "$vp:$n $from -> $to"; done
    mg_vwrite "$vp" < "$out"
    MG_EDITED+=("$vp"); mg_plan "$vp"
}

